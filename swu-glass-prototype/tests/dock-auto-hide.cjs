const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>localStorage.setItem('swu-glass:lighting-mode','"day"'));
  await page.goto('http://127.0.0.1:5180/?mode=demo');
  const handle=page.getByRole('button',{name:'展开导航栏',exact:true}),dock=page.locator('.dock');
  assert.equal(await handle.count(),1,'browsing exposes the bottom handle');
  assert.equal(await handle.getAttribute('aria-expanded'),'false');
  assert.equal(await page.getByRole('navigation',{name:'主导航'}).count(),0,'hidden navigation is excluded from accessibility');
  const light=await handle.locator('span').evaluate(e=>getComputedStyle(e).backgroundColor);
  await page.screenshot({path:'docs/dock-hidden.png'});
  const content=await page.locator('.content-grid').boundingBox();
  const trigger=await handle.boundingBox();
  await handle.hover();
  await page.waitForTimeout(300);
  const revealed=await dock.boundingBox();
  assert.ok(Math.abs(trigger.y+trigger.height/2-revealed.y-revealed.height/2)<1,'handle and revealed Dock share the same vertical center');
  assert.ok(Math.abs(trigger.x+trigger.width/2-revealed.x-revealed.width/2)<1,'handle and revealed Dock share the same horizontal center');
  assert.ok(await page.evaluate(({x,y})=>!!document.elementFromPoint(x,y)?.closest('nav.dock'),{x:trigger.x+trigger.width/2,y:trigger.y+trigger.height/2}),'pointer lands directly inside the revealed navigation');
  assert.equal(await handle.getAttribute('aria-expanded'),'true');
  await page.getByRole('button',{name:'日程',exact:true}).hover();
  assert.equal(await handle.getAttribute('aria-expanded'),'true','moving from the handle into icons keeps the Dock open');
  await page.screenshot({path:'docs/dock-expanded.png'});
  assert.equal((await page.locator('.content-grid').boundingBox()).height,content.height,'revealing does not reflow content');
  await page.getByRole('button',{name:'日程',exact:true}).click();
  await page.getByRole('heading',{name:'日程',exact:true}).waitFor();
  await page.mouse.move(30,30);await page.waitForTimeout(280);
  assert.equal(await handle.getAttribute('aria-expanded'),'false','mouse navigation still hides on departure');
  await handle.focus();await page.keyboard.press('Tab');
  assert.equal(await page.getByRole('button',{name:'首页',exact:true}).evaluate(e=>document.activeElement===e),true);
  assert.equal(await handle.getAttribute('aria-expanded'),'true');
  await page.keyboard.press('Escape');await page.waitForTimeout(280);
  assert.equal(await handle.getAttribute('aria-expanded'),'false');
  assert.equal(await handle.evaluate(e=>document.activeElement===e),true);
  await handle.hover();await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.getByLabel('光线氛围',{exact:true}).selectOption('moonlight');
  await page.mouse.move(30,30);await page.waitForTimeout(280);
  const dark=await handle.locator('span').evaluate(e=>getComputedStyle(e).backgroundColor);
  assert.notEqual(dark,light,'handle adapts to dark content');
  await page.emulateMedia({reducedMotion:'reduce'});
  await handle.hover();
  assert.equal(await dock.evaluate(e=>getComputedStyle(e).transitionDuration),'0s');
  await page.mouse.move(30,30);
  assert.equal(await handle.getAttribute('aria-expanded'),'false');
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  await mobile.goto('http://127.0.0.1:5180/?mode=demo');
  const tapHandle=mobile.getByRole('button',{name:'展开导航栏',exact:true});
  await tapHandle.tap();
  assert.equal(await tapHandle.getAttribute('aria-expanded'),'true');
  await mobile.getByRole('button',{name:'日程',exact:true}).tap();
  await mobile.getByRole('heading',{name:'日程',exact:true}).waitFor();
  assert.equal(await tapHandle.getAttribute('aria-expanded'),'false','touch navigation closes the Dock');
  await tapHandle.tap();await mobile.getByRole('heading',{name:'日程',exact:true}).tap();
  assert.equal(await tapHandle.getAttribute('aria-expanded'),'false','outside touch dismisses');
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  assert.deepEqual(errors,[]);
  console.log('Dock auto-hide passed: handle, hover continuity, no reflow, mouse exit, keyboard/Escape, dark theme, reduced motion and touch.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
